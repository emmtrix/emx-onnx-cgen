"""Assemble the official ONNX backend test data in this directory.

The official-file tests, their expectation files and the recorded ``verify``
command lines address the ONNX backend test models below this directory. Only
this script and ``README.md`` are tracked; everything else is assembled from
the installed onnx package:

* ``node/``: since onnx 1.23 (onnx/onnx#7959) neither the onnx repository nor
  the wheel ships these files; upstream builds the node tests in memory from
  ``onnx.backend.test.case.node``. They are written in the pre-1.23 layout
  (``model.onnx`` plus ``test_data_set_N/{input,output}_K.pb``).
* all other kinds (``light/``, ``pytorch-*``, ``real/``, ``simple/``) are
  copied from ``onnx/backend/test/data`` of the installed wheel.

The data must come from the onnx version pinned in ``requirements-ci.txt``,
because the expectation files record its models and reference outputs.

pytest runs this on startup (``tests/conftest.py``). Run
``python onnx-backend-test-data/generate.py`` to build the data outside of
pytest, e.g. before reproducing a single ``verify`` command line.
"""

from __future__ import annotations

import logging
import os
import re
import shutil
import sys
import warnings
from pathlib import Path
from typing import Any

LOGGER = logging.getLogger(__name__)

BACKEND_TEST_DATA_ROOT = Path(__file__).resolve().parent
REPO_ROOT = BACKEND_TEST_DATA_ROOT.parent
REQUIREMENTS_PATH = REPO_ROOT / "requirements-ci.txt"
VERSION_STAMP_NAME = ".onnx-version"
# Tracked files of this directory; every other entry is generated.
TRACKED_NAMES = frozenset({"README.md", "generate.py", "__pycache__"})
# Generated by the previous scheme (onnx 1.23 upgrade) inside the submodule
# checkout; removed once so that the submodule working tree is clean again.
LEGACY_NODE_DATA_ROOT = (
    REPO_ROOT / "onnx-org" / "onnx" / "backend" / "test" / "data" / "node"
)
_ONNX_PIN = re.compile(r"^onnx==(?P<version>[^\s;#]+)", re.MULTILINE)


class BackendTestDataError(RuntimeError):
    """The backend test data cannot be generated for the pinned onnx version."""


def _pinned_onnx_version() -> str:
    match = _ONNX_PIN.search(REQUIREMENTS_PATH.read_text(encoding="utf-8"))
    if match is None:
        raise BackendTestDataError(f"No onnx==<version> pin in {REQUIREMENTS_PATH}.")
    return match.group("version")


def _stamped_version(root: Path) -> str | None:
    stamp = root / VERSION_STAMP_NAME
    if not stamp.exists():
        return None
    return stamp.read_text(encoding="utf-8").strip()


def _to_proto(value: Any, value_info: Any) -> Any:
    from onnx import TensorProto, numpy_helper

    value_type = value_info.type
    if value_type.HasField("map_type"):
        return numpy_helper.from_dict(value, value_info.name)
    if value_type.HasField("sequence_type"):
        return numpy_helper.from_list(value, value_info.name)
    if value_type.HasField("optional_type"):
        return numpy_helper.from_optional(value, value_info.name)
    if isinstance(value, TensorProto):
        return value
    return numpy_helper.from_array(value, value_info.name)


def _write_node_case(case: Any, case_dir: Path) -> None:
    case_dir.mkdir(parents=True)
    graph = case.model.graph
    (case_dir / "model.onnx").write_bytes(case.model.SerializeToString())
    for set_index, (inputs, outputs) in enumerate(case.data_sets):
        data_set_dir = case_dir / f"test_data_set_{set_index}"
        data_set_dir.mkdir()
        for index, value in enumerate(inputs):
            proto = _to_proto(value, graph.input[index])
            (data_set_dir / f"input_{index}.pb").write_bytes(proto.SerializeToString())
        for index, value in enumerate(outputs):
            proto = _to_proto(value, graph.output[index])
            (data_set_dir / f"output_{index}.pb").write_bytes(proto.SerializeToString())


def _generate_node_tests(target: Path) -> None:
    from onnx.backend.test.case.node import collect_testcases

    # The upstream case definitions compute some expected outputs that are
    # intentionally inf/nan; their numpy RuntimeWarnings are noise here.
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)
        cases = collect_testcases(None)
    for case in cases:
        _write_node_case(case, target / case.name)
    LOGGER.info("Generated %d ONNX node backend tests in %s", len(cases), target)


def _copy_shipped_tests(target: Path) -> None:
    import onnx

    shipped_root = Path(onnx.__file__).resolve().parent / "backend" / "test" / "data"
    for kind_dir in sorted(shipped_root.iterdir()):
        if kind_dir.is_dir() and kind_dir.name != "node":
            shutil.copytree(kind_dir, target / kind_dir.name)


def _remove_generated_entries(root: Path, keep: Path) -> None:
    for entry in root.iterdir():
        if entry.name in TRACKED_NAMES or entry == keep:
            continue
        if entry.is_dir():
            shutil.rmtree(entry)
        else:
            entry.unlink()


def _remove_legacy_node_data() -> None:
    if _stamped_version(LEGACY_NODE_DATA_ROOT) is not None:
        shutil.rmtree(LEGACY_NODE_DATA_ROOT, ignore_errors=True)


def ensure_backend_test_data(root: Path = BACKEND_TEST_DATA_ROOT) -> None:
    """Assemble the backend test data below ``root`` unless it is up to date.

    Raises :class:`BackendTestDataError` when the installed onnx package is not
    the pinned version, because its models and reference outputs would not
    match the recorded expectations.
    """
    import onnx

    _remove_legacy_node_data()
    pinned_version = _pinned_onnx_version()
    if onnx.__version__ != pinned_version:
        raise BackendTestDataError(
            f"Installed onnx {onnx.__version__} does not match the pinned "
            f"onnx=={pinned_version} (see requirements-ci.txt); install it to "
            "generate the ONNX backend test data."
        )
    if _stamped_version(root) == pinned_version:
        return
    # Build in a staging directory, move it into place and write the version
    # stamp last, so that an interrupted run is rebuilt on the next start.
    staging = root / f".build-{os.getpid()}"
    shutil.rmtree(staging, ignore_errors=True)
    staging.mkdir(parents=True)
    try:
        _copy_shipped_tests(staging)
        _generate_node_tests(staging / "node")
        _remove_generated_entries(root, keep=staging)
        for entry in sorted(staging.iterdir()):
            entry.rename(root / entry.name)
        (root / VERSION_STAMP_NAME).write_text(pinned_version + "\n", encoding="utf-8")
    finally:
        shutil.rmtree(staging, ignore_errors=True)


def main() -> int:
    logging.basicConfig(level=logging.INFO)
    try:
        ensure_backend_test_data()
    except BackendTestDataError as error:
        print(error, file=sys.stderr)
        return 1
    print(BACKEND_TEST_DATA_ROOT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
